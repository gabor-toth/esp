static void draw_logo() {
    int width = u8g2_GetDisplayWidth(&u8g2);
    int height = u8g2_GetDisplayHeight(&u8g2);
    u8g2_ClearBuffer(&u8g2);
    u8g2_SetDrawColor(&u8g2, 1);
    int x = (width - yanmar_seeklogo_width) / 2;
    int y = (height - yanmar_seeklogo_height) / 2;
    u8g2_DrawXBM(&u8g2, x, y, yanmar_seeklogo_width, yanmar_seeklogo_height, yanmar_seeklogo_bits);
    u8g2_SendBuffer(&u8g2);
}

static void screen_onoff(bool on) {
    u8g2_SetPowerSave(&u8g2, !on); // wake up display
    gpio_set_level(PIN_LCD_BACKLIGHT, on);
    gpio_set_level(PIN_BUTTON_BACKLIGHT, on);
    engine_display_is_on = on;
}

_Noreturn static void task_display(void *arg) {
    (void) arg;

    for (;;) {
        int mode;

        if (!xQueueReceive(display_event_queue, &mode, portMAX_DELAY)) {
            continue;
        }
        switch (mode) {
            case CMD_DRAW_LOGO:
                draw_logo();
                break;
            case CMD_DRAW_SCREEN:
                draw_screen();
                break;
            case CMD_SCREEN_ON:
                screen_onoff(true);
                break;
            case CMD_SCREEN_OFF:
                screen_onoff(false);
                break;
            default:
                break;
        }
    }
}

void engine_display_setup_display() {
    u8g2_esp32_hal_t u8g2_esp32_hal = U8G2_ESP32_HAL_DEFAULT;
    u8g2_esp32_hal.bus.spi.clk = PIN_LCD_CLK;
    u8g2_esp32_hal.bus.spi.cs = PIN_LCD_CS;
    u8g2_esp32_hal.bus.spi.mosi = PIN_LCD_MOSI;
    u8g2_esp32_hal.reset = PIN_LCD_RESET;
    u8g2_esp32_hal_init(u8g2_esp32_hal);

    u8g2_Setup_st7565_ea_dogm128_f(
        &u8g2, U8G2_R2, u8g2_esp32_spi_byte_cb,
        u8g2_esp32_gpio_and_delay_cb); // init u8g2 structure

    // u8g2_m_16_8_f
    u8g2_Setup_st7920_s_128x64_f(
        &u8g2, U8G2_R2, u8g2_esp32_spi_byte_cb,
        u8g2_esp32_gpio_and_delay_cb); // init u8g2 structure

    u8g2_InitDisplay(&u8g2); // send init sequence to the display, display is in sleep mode after this

    int width = u8g2_GetDisplayWidth(&u8g2);
    int height = u8g2_GetDisplayHeight(&u8g2);
    ESP_LOGI(TAG, "display is %dx%d", width, height);

    display_event_queue = xQueueCreate(10, sizeof( int ));
    xTaskCreate(task_display, TAG, 3072, nullptr, 10, nullptr);
}

void engine_display_draw_screen(const char *cause) {
    ESP_LOGI(TAG, "draw screen because %s", cause);
    int mode = CMD_DRAW_SCREEN;
    xQueueSendToBack(display_event_queue, &mode, 0);
}

void engine_display_draw_logo() {
    ESP_LOGI(TAG, "draw logo");
    int mode = CMD_DRAW_LOGO;
    xQueueSendToBack(display_event_queue, &mode, 0);
}

void engine_display_onoff(bool on) {
    ESP_LOGI(TAG, "turning display %s", on ? "on" : "off");
    int mode = on ? CMD_SCREEN_ON : CMD_SCREEN_OFF;
    xQueueSendToBack(display_event_queue, &mode, 0);
}
